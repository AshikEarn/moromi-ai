        function normalizeText(value) {
            return String(value || "")
                .toLowerCase()
                .replace(/[“”‘’]/g, '"')
                .replace(/\s+/g, " ")
                .trim();
        }

        function pickRandom(list) {
            return list[Math.floor(Math.random() * list.length)];
        }

        function getOfflineReply(message, userName = "") {
            const text = normalizeText(message);

            if (!text) {
                return "আপনার মনের কথা বা প্রশ্নটি একটু লিখুন। কী নিয়ে কথা বলতে চান?";
            }

            const scores = {};

            for (const [category, words] of Object.entries(KEYWORDS)) {
                let score = 0;
                for (const word of words) {
                    if (text.includes(normalizeText(word))) score++;
                }
                if (score > 0) scores[category] = score;
            }

            let category = "general";
            const ranked = Object.entries(scores).sort((a, b) => b[1] - a[1]);

            if (ranked.length > 0) {
                const highest = ranked[0][1];
                const tied = ranked
                    .filter(item => item[1] === highest)
                    .map(item => item[0]);
                category = pickRandom(tied);
            }

            let reply = pickRandom(OFFLINE_BANK[category] || OFFLINE_BANK.general);

            if (
                userName &&
                /^(হাই|হ্যালো|hi|hello|hey|salam|আসসালামু)/i.test(text)
            ) {
                reply = reply.replace("আমি মরমী।", `আমি মরমী। ${userName},`);
            }

            return reply;
        }

        function addMessage(text, className, save = true) {
            const messageDiv = document.createElement('div');
            messageDiv.classList.add('message', className);

            if (className === 'bot-message') {
                const label = document.createElement('span');
                label.className = 'bot-label';
                label.innerText = '🌿 মরমী • Offline Bot';
                messageDiv.appendChild(label);
            }

            const content = document.createElement('span');
            content.innerText = text;
            messageDiv.appendChild(content);

            chatMessages.insertBefore(messageDiv, typingIndicator);
            chatMessages.scrollTop = chatMessages.scrollHeight;

            if (save) {
                saveChatMessage(text, className);
            }
        }

        function saveChatMessage(text, className) {
            const history = JSON.parse(localStorage.getItem('moromi_chat_history') || '[]');
            history.push({
                text,
                className,
                time: Date.now()
            });

            if (history.length > 100) {
                history.splice(0, history.length - 100);
            }

            localStorage.setItem('moromi_chat_history', JSON.stringify(history));
        }

        function loadChatHistory() {
            const history = JSON.parse(localStorage.getItem('moromi_chat_history') || '[]');

            history.forEach(item => {
                addMessage(item.text, item.className, false);
            });
        }


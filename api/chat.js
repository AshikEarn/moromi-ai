export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const { message, userName } = req.body;
  
  if (!message) {
    return res.status(400).json({ error: 'Message is required.' });
  }

  const text = message.toLowerCase();
  let reply = "";
  const name = userName || 'বন্ধু';

  try {
    // ১. নেশা বা মাদক আসক্তি থেকে মুক্তির উপায়
    if (
      text.includes("নেশায় আসক্ত") ||
      text.includes("নেশা ছাড়তে") ||
      text.includes("মাদক ছাড়তে") ||
      text.includes("মাদকে আসক্ত")
    ) {
      reply = `দেখুন ${name}, আপনি যে এই সত্যটি স্বীকার করেছেন এবং মুক্ত হতে চাচ্ছেন, এটিই আপনার জীবনের সবচেয়ে বড় ও সাহসি প্রথম পদক্ষেপ। নেশা থেকে মুক্ত হতে হলে:\n১. খারাপ সঙ্গ ও পুরোনো পরিবেশ থেকে একদম দূরে সরে যান।\n২. পরিবার বা বিশ্বস্ত কারো সাহায্য নিন, প্রয়োজনে রিহ্যাব সেন্টারের সহায়তা নিন।\n৩. প্রতিদিন শরীরচর্চা করুন এবং মনকে অন্য কোনো ভালো কাজে ব্যস্ত রাখুন। আল্লাহ আপনাকে অবশ্যই শক্তি দেবেন, বিশ্বাস রাখুন।`;
    }

    // ২. জুয়া বা বেটিং আসক্তি থেকে মুক্তির উপায়
    else if (
      text.includes("জুয়ায় আসক্ত") ||
      text.includes("জুয়া ছাড়তে") ||
      text.includes("বেটিং আসক্ত") ||
      text.includes("জুয়ার নেশা")
    ) {
      reply = `${name}, অনলাইন জুয়া বা বেটিং হলো তুষের আগুন, যা আস্তে আস্তে সব শেষ করে দেয়। জুয়া থেকে বাঁচার উপায়:\n১. প্রথমে আপনার মোবাইল থেকে সমস্ত বেটিং অ্যাপ বা লিংক আনইনস্টল করে দিন।\n২. টাকার হিসাব অন্য কারো কাছে রাখুন বা এমন কারো নজরদারিতে থাকুন যে আপনাকে আটকে রাখবে।\n৩. মাথায় রাখবেন, জুয়ায় হেরে যাওয়া টাকা কোনোদিন জুয়া খেলে ফিরিয়ে আনা যায় না। কঠোর হোন, তওবা করে ফিরে আসুন।`;
    }

    // ৩. ৫ ওয়াক্ত নামাজ পড়ার উপায়
    else if (
      text.includes("নামাজ পড়তে চাই") ||
      text.includes("নামাজ পড়তে চাই") ||
      text.includes("৫ ওয়াক্ত নামাজ") ||
      text.includes("পাঁচ ওয়াক্ত নামাজ")
    ) {
      reply = `মাশাআল্লাহ ${name}! আপনার এই নিয়তটি মহান আল্লাহর কাছে অনেক পছন্দ হয়েছে। ৫ ওয়াক্ত নামাজ নিয়মিত শুরু করার ছোট কিছু টিপস:\n১. আজ থেকেই আজান দেওয়ার সাথে সাথে সব কাজ ফেলে অজু করে নিন।\n২. একা একা শুরু করতে সমস্যা হলে কাছের মসজিদে গিয়ে জামাতে পড়ার অভ্যাস করুন।\n৩. নিয়ত করুন যে দুনিয়ার যেকোনো ব্যস্ততাই আসুক, নামাজের সময় নামাজই আগে পড়বেন। আল্লাহ আপনার জন্য পথ সহজ করে দেবেন।`;
    }

    // ৪. টাকা জমানোর উপায়
    else if (
      text.includes("টাকা জমে") ||
      text.includes("টাকা জমানোর") ||
      text.includes("সঞ্চয়") ||
      text.includes("টাকা জমাবো")
    ) {
      reply = `টাকা জমানোর সবচেয়ে কার্যকরী নিয়ম হলো '50/30/20 রুল' বা আগে সেভিংস করা ${name}।\n১. হাত বা পকেটে টাকা আসা মাত্রই সেখান থেকে নির্দিষ্ট কিছু অংশ (যেমন ১০% বা ২০%) আলাদা করে জমিয়ে ফেলুন, বাকিটা খরচ করুন।\n২. অপ্রয়োজনীয় কেনাকাটা বা শৌখিন খরচ কমিয়ে দিন।\n৩. ছোট ছোট সঞ্চয় থেকেই বড় পুঁজি তৈরি হয়। ধৈর্য ধরে আজ থেকেই একটি গোল সেট করুন!`;
    }

    // ৫. মন খারাপ বা দুঃখ সংক্রান্ত
    else if (
      text.includes("মন খারাপ") ||
      text.includes("দুঃখ") ||
      text.includes("কষ্ট") ||
      text.includes("কান্না") ||
      text.includes("বিষণ্ণ") ||
      text.includes("sad")
    ) {
      reply = `মন খারাপ বা দুশ্চিন্তা হলে এক গ্লাস ঠাণ্ডা পানি খেয়ে একটু দীর্ঘশ্বাস নিন, ${name}। মনে রাখবেন, আল্লাহ তাআলা কোনো বান্দাকে তার সাধ্যের বাইরে কষ্ট দেন না। বেশি বেশি 'লা হাওলা ওয়া লা কুওয়াতা ইল্লা বিল্লাহ' পাঠ করুন।`;
    }

    // ৬. রাগ ও সম্পর্ক
    else if (
      text.includes("রাগ") ||
      text.includes("ঝগড়া") ||
      text.includes("ঝগড়া") ||
      text.includes("সম্পর্ক") ||
      text.includes("ভালোবাসা")
    ) {
      reply = `রাগের সময় সিদ্ধান্ত না নেওয়াই ভালো, ${name}। 🌿 কিছুক্ষণ বিরতি নিন, শান্ত হন এবং পরে সমস্যাটা নিয়ে কথা বলুন। কাউকে হারানোর জন্য নয়, সমস্যা সমাধানের জন্য কথা বলুন।`;
    }

    // ৭. সালাম ও হ্যালো
    else if (
      text.includes("হাই") ||
      text.includes("হ্যালো") ||
      text.includes("hello") ||
      text.includes("hi") ||
      text.includes("সালাম") ||
      text.includes("আসসালামু")
    ) {
      reply = `আসসালামু আলাইকুম ${name} 🌸 আমি মরমী। আজ কেমন আছেন? আপনার মনের কথা বা জীবনের যেকোনো সমস্যা নিয়ে আমার সাথে কথা বলতে পারেন।`;
    }

    // ৮. ডিফল্ট বা অন্য কোনো প্রশ্ন
    else {
      reply = `আপনার কথাটি বুঝতে পেরেছি, ${name}। 🌿 মরমী একটি ফ্রি অফলাইন সহকারী বট। আপনি মাদক, জুয়া, নামাজ, টাকা জমানো, মন খারাপ বা জীবনের যেকোনো গুরুত্বপূর্ণ বিষয়ে প্রশ্ন করতে পারেন। আপনার প্রশ্নটি আরেকটু স্পষ্ট করে লিখবেন?`;
    }

    return res.status(200).json({
      reply: reply,
      mode: "offline"
    });

  } catch (error) {
    console.error(error);
    return res.status(500).json({
      error: "মরমীর উত্তর তৈরি করতে সমস্যা হয়েছে। আবার চেষ্টা করুন।"
    });
  }
}
